#!/usr/bin/env python3
"""Generate pure validation rules from the pinned configuration schema, no runtime I/O."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[2]
schema = json.loads((root / 'tests/Fixtures/Configuration/morphir-config-v1.json').read_text())

# Local amendments (add-fsharp-compile, VER-1 and SRC-2; generate --extension, codegen tables). The pinned upstream fixture stays unchanged; these
# changes are applied to the parsed schema before generation, and PROVENANCE.md records them.
SEMVER = (r'^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)'
          r'(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?(\+[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$')


def amend(schema):
    # 1. ir.format_version is an integer classic version or a SemVer string with optional pre-release and
    #    build parts (VER-1).
    ir = schema['properties']['ir']['properties']
    integer = ir['format_version']
    ir['format_version'] = {'anyOf': [integer, {'type': 'string', 'pattern': SEMVER}]}
    # 2. Every [frontend.<language>] table has the same members project_file and extension, defined once (SRC-2).
    frontend = schema['properties']['frontend']
    elm = frontend['properties']['elm']
    extension = elm['properties'].pop('extension')
    schema.setdefault('definitions', {})['frontendLanguage'] = {
        'type': 'object',
        'properties': {
            'extension': extension,
            'project_file': {'type': 'string', 'minLength': 1},
        },
    }
    frontend['properties']['elm'] = {'allOf': [{'$ref': '#/definitions/frontendLanguage'}, elm]}
    frontend['additionalProperties'] = {'$ref': '#/definitions/frontendLanguage'}
    # 3. Every [codegen.<target>] table has the member extension: the backend extension of that target, as
    #    [frontend.<language>].extension names a frontend extension (generate --extension).
    codegen = schema['properties']['codegen']
    schema['definitions']['codegenTarget'] = {
        'type': 'object',
        'properties': {'extension': dict(extension)},
    }
    codegen['additionalProperties'] = {'$ref': '#/definitions/codegenTarget'}
    return schema


schema = amend(schema)


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def seq(values):
    return '[ ' + '; '.join(values) + ' ]'


def rules(node):
    output = []
    if '$ref' in node:
        output.append('Reference ' + quoted(node['$ref'].split('/')[-1]))
    if 'type' in node:
        output.append('Kind ' + quoted(node['type']))
    if 'enum' in node:
        output.append('Choice ' + seq('ConfigValue.String ' + quoted(v) for v in node['enum']))
    properties = node.get('properties', {})
    for key, child in properties.items():
        output.append('Property (' + quoted(key) + ', ' + rules(child) + ')')
    if 'required' in node:
        output.append('Required ' + seq(map(quoted, node['required'])))
    additional = node.get('additionalProperties', True)
    if additional is False:
        output.append('Closed ' + seq(map(quoted, properties)))
    elif isinstance(additional, dict):
        output.append('Additional (' + seq(map(quoted, properties)) + ', ' + rules(additional) + ')')
    if 'items' in node:
        items = node['items']
        if isinstance(items, list):
            extra = node.get('additionalItems', True)
            extra_rules = rules(extra) if isinstance(extra, dict) else ('[]' if extra else '[ Reject "Additional array elements are forbidden." ]')
            output.append('TupleItems (' + seq(map(rules, items)) + ', ' + extra_rules + ')')
        else:
            output.append('Elements ' + rules(items))
    for source, target in [('minimum', 'Minimum'), ('maximum', 'Maximum'), ('minLength', 'MinLength'), ('minItems', 'MinItems')]:
        if source in node:
            output.append(target + ' ' + str(node[source]))
    if 'pattern' in node:
        output.append('Pattern ' + quoted(node['pattern']))
    for source, target in [('anyOf', 'Any'), ('oneOf', 'One'), ('allOf', 'All')]:
        if source in node:
            output.append(target + ' ' + seq(map(rules, node[source])))
    if 'not' in node:
        output.append('Not ' + rules(node['not']))
    return seq(output)

text = '''namespace Morphir.Configuration

// Generated by scripts/configuration/generate-schema.py from the pinned fixture and its local amendments.
// Schema SHA-256 b5b2f636b8fbbdcc4dc3636ffe7bcee81776d0dbd73810d9c9391f1ee2813901.
// Amendments: ir.format_version takes a SemVer string; every [frontend.<language>] table has project_file and extension;
// every [codegen.<target>] table has extension.
module internal ConfigurationSchema =
    type Rule =
        | Reference of string
        | Kind of string
        | Choice of ConfigValue list
        | Property of string * Rule list
        | Required of string list
        | Closed of string list
        | Additional of string list * Rule list
        | Elements of Rule list
        | TupleItems of Rule list list * Rule list
        | Minimum of int
        | Maximum of int
        | MinLength of int
        | MinItems of int
        | Pattern of string
        | Any of Rule list list
        | One of Rule list list
        | All of Rule list list
        | Not of Rule list
        | Reject of string

    let definitions = Map.ofList [
'''
for key, value in schema.get('definitions', {}).items():
    text += '        ' + quoted(key) + ', ' + rules(value) + '\n'
text += '    ]\n\n    let root = ' + rules(schema) + '\n'
output = root / 'src/Morphir.Configuration/Schema.fs'
output.write_text(text)
subprocess.run(['dotnet', 'fantomas', str(output)], cwd=root, check=True)
