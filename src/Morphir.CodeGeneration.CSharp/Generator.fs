namespace Morphir.CodeGeneration.CSharp

open System
open System.Globalization
open System.Threading
open Morphir.IR
open Morphir.IR.Classic
open Morphir.IR.Model

module internal Foundation =
    let fail rule location message =
        raise (
            Refusal
                {
                    Rule = rule
                    Location = location
                    Message = message
                }
        )

    let name = TypeEmission.identifier

    let package = TypeEmission.packageName

    let moduleName = TypeEmission.moduleName

    let unwrap =
        function
        | Documented.WithDocumentation(_, x)
        | Documented.WithoutDocumentation x -> x

    let sources naming (model: VersionedModel) (ct: CancellationToken) =
        let initialCatalog, _ = TypeEmission.prepare naming model ct

        let checkedValues =
            ValueLowering.declarations model ct
            |> ValueLowering.check initialCatalog ct

        let records = ValueLowering.recordDeclarations initialCatalog model ct checkedValues
        let catalog, types = TypeEmission.prepareWith naming records model ct
        let values = ValueEmission.emit naming catalog ct checkedValues

        let sources pkg modules =
            ct.ThrowIfCancellationRequested()

            if not (List.isEmpty modules) then
                TypeEmission.validateModules
                    ct
                    pkg
                    (modules
                     |> List.map (fun (path, _, names) -> path, names))

            for path, _, names in modules do
                ct.ThrowIfCancellationRequested()

                for name in names do
                    ct.ThrowIfCancellationRequested()

                    for declaration in
                        catalog
                        |> Map.toList
                        |> List.map snd do
                        ct.ThrowIfCancellationRequested()

                        let emitted =
                            match declaration.Definition with
                            | TypeEmission.Cases _ -> true
                            | TypeEmission.Alias(TypeEmission.Fields _ as body) ->
                                let owner, _ =
                                    TypeEmission.recordTarget ct catalog declaration.Location body

                                owner.Name = declaration.Name
                            | _ -> false

                        if
                            emitted
                            && declaration.Name.ModulePath = path
                            && TypeEmission.identifier declaration.Name.LocalName = TypeEmission.identifier
                                name
                        then
                            fail
                                "name-collision"
                                declaration.Location
                                (TypeEmission.title name
                                 + " shares an emitted type and value identity.")

            modules
            |> List.map (fun (path, isPublic, _) ->
                ct.ThrowIfCancellationRequested()
                let ns = TypeEmission.namespaceName naming pkg
                let moduleId = moduleName path
                let access = if isPublic then "public" else "internal"

                {
                    RelativePath = TypeEmission.sourcePath pkg path
                    Text =
                        $"// <auto-generated/>\n#nullable enable\nnamespace {ns};\n{access} static class {moduleId}\n{{\n"
                        + (Map.tryFind path types
                           |> Option.defaultValue "")
                        + (Map.tryFind path values
                           |> Option.defaultValue "")
                        + "}\n"
                }
            )

        match model.Distribution with
        | DistributionModel.Classic(Distribution.Library(pkg, _, definition)) ->
            definition.Modules
            |> Map.toList
            |> List.map (fun (path, modul) ->
                path,
                modul.Access = AccessControlled.Public,
                modul.Value.Values
                |> Map.toList
                |> List.map fst
            )
            |> sources pkg
        | DistributionModel.V4(Morphir.IR.V4.Library(pkg, _, definition)) ->
            definition.Modules
            |> Morphir.IR.V4.OrderedMap.toList
            |> List.sortBy fst
            |> List.map (fun (path, modul) ->
                path,
                modul.Access = Morphir.IR.V4.Public,
                modul.Value.Values
                |> Morphir.IR.V4.OrderedMap.toList
                |> List.map fst
            )
            |> sources pkg
        | _ ->
            fail
                "unsupported-distribution"
                "$"
                "Only admitted Library distributions can be generated."

/// In-memory generation. The caller owns decoding, host configuration and publication.
[<AbstractClass; Sealed>]
type CSharpGenerator private () =
    static member private GenerateCore
        (
            model: VersionedModel,
            options: GenerationOptions,
            namespaceOverride: NamespaceOverride option,
            cancellationToken: CancellationToken
        ) =
        let result status sources diagnostics = {
            Status = status
            Family = model.Family
            SourceVersion = model.SourceVersion.Text
            LanguageVersion = options.LanguageVersion
            Sources = sources
            Diagnostics = diagnostics
            Runtime = {
                TargetFramework = "net10.0"
                Package = "Morphir.SDK.CSharp"
            }
        }

        try
            cancellationToken.ThrowIfCancellationRequested()

            if
                namespaceOverride
                |> Option.exists (fun value -> obj.ReferenceEquals(value, null))
            then
                Foundation.fail
                    "invalid-namespace"
                    "$options/namespace"
                    "An explicit namespace override must be validated and non-null."

            if
                options.LanguageVersion
                <> 14
                && options.LanguageVersion
                   <> 15
            then
                Foundation.fail
                    "unsupported-language"
                    "$options/languageVersion"
                    "Only numeric C# 14 and 15 are supported."

            let versions =
                if model.Family = ModelFamily.Classic then
                    [ "1"; "2"; "3"; "3.0.0"; "3.1.0" ]
                else
                    [ "4"; "4.0.0" ]

            if not (List.contains model.SourceVersion.Text versions) then
                Foundation.fail
                    "unsupported-version"
                    "$sourceVersion"
                    "The source version is not supported for this model family."

            let package =
                match model.Distribution with
                | DistributionModel.Classic(Distribution.Library(pkg, _, _)) -> Some pkg
                | DistributionModel.V4(Morphir.IR.V4.Library(pkg, _, _)) -> Some pkg
                | _ -> None

            let naming: TypeEmission.Naming = {
                Package = package
                Namespace =
                    namespaceOverride
                    |> Option.map (fun value -> value.Value)
            }

            let sources = Foundation.sources naming model cancellationToken
            cancellationToken.ThrowIfCancellationRequested()
            result GenerationStatus.Success sources []
        with
        | :? OperationCanceledException when cancellationToken.IsCancellationRequested ->
            result GenerationStatus.Cancelled [] []
        | Refusal diagnostic -> result GenerationStatus.Failure [] [ diagnostic ]

    static member Generate
        (
            model: VersionedModel,
            options: GenerationOptions,
            cancellationToken: CancellationToken
        ) =
        CSharpGenerator.GenerateCore(model, options, None, cancellationToken)

    static member Generate
        (
            model: VersionedModel,
            options: GenerationOptions,
            namespaceOverride: NamespaceOverride,
            cancellationToken: CancellationToken
        ) =
        CSharpGenerator.GenerateCore(model, options, Some namespaceOverride, cancellationToken)
