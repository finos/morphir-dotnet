namespace Morphir.CodeGeneration.CSharp

open System
open System.Globalization
open System.Threading
open Morphir.IR
open Morphir.IR.Classic
open Morphir.IR.Model

exception internal Refusal of GenerationDiagnostic

module internal Foundation =
    let fail rule location message =
        raise (
            Refusal
                {
                    Rule = rule
                    Location = location
                    Message = message
                }
        )

    let name n =
        "@"
        + Name.toTitleCase n

    let package (PackageName(Path parts)) =
        parts
        |> List.map name
        |> String.concat "."

    let moduleName (ModulePath(Path parts)) =
        parts
        |> List.map name
        |> String.concat "_"

    let unwrap =
        function
        | Documented.WithDocumentation(_, x)
        | Documented.WithoutDocumentation x -> x

    let sources (model: VersionedModel) (ct: CancellationToken) =
        match model.Distribution with
        | DistributionModel.Classic(Distribution.Library(pkg, _, definition)) ->
            definition.Modules
            |> Map.toList
            |> List.map (fun (path, controlled) ->
                ct.ThrowIfCancellationRequested()

                let location =
                    "$modules/"
                    + string path

                if not controlled.Value.Types.IsEmpty then
                    fail "unsupported-type" location "Type lowering is not yet admitted."

                let members =
                    controlled.Value.Values
                    |> Map.toList
                    |> List.map (fun (key, controlled) ->
                        ct.ThrowIfCancellationRequested()
                        let definition = unwrap controlled.Value

                        match definition.InputTypes, definition.OutputType, definition.Body with
                        | [],
                          Type.Reference(_, fq, []),
                          Value.Literal(_, WholeNumberLiteral number) when
                            FQName.toString fq = "Morphir.SDK.Basics.Int"
                            && number
                               >= int64 Int32.MinValue
                            && number
                               <= int64 Int32.MaxValue
                            ->
                            let access =
                                if controlled.Access = AccessControlled.Public then
                                    "public"
                                else
                                    "internal"

                            $"    {access} static int {name key}() => {number.ToString(CultureInfo.InvariantCulture)};\n"
                        | _ ->
                            fail
                                "unsupported-expression"
                                (location
                                 + "/values/"
                                 + Name.toCamelCase key)
                                "The expression has no admitted mapping."
                    )

                let ns = package pkg
                let moduleId = moduleName path

                {
                    RelativePath =
                        (ns
                         + "/"
                         + moduleId
                         + ".g.cs")
                            .Replace("@", "")
                    Text =
                        $"// <auto-generated/>\nnamespace {ns};\npublic static class {moduleId}\n{{\n"
                        + String.concat "" members
                        + "}\n"
                }
            )
        | DistributionModel.V4(Morphir.IR.V4.Library(_, _, definition)) when
            Morphir.IR.V4.OrderedMap.count definition.Modules = 0
              ->
              []
        | _ ->
            fail
                "unsupported-distribution"
                "$"
                "Only admitted Library distributions can be generated."

/// In-memory generation. The caller owns decoding, host configuration and publication.
[<AbstractClass; Sealed>]
type CSharpGenerator private () =
    static member Generate
        (
            model: VersionedModel,
            options: GenerationOptions,
            cancellationToken: CancellationToken
        ) =
        let result status sources diagnostics = {
            Status = status
            Family = model.Family
            SourceVersion = model.SourceVersion.Text
            LanguageVersion = options.LanguageVersion
            Sources = sources
            Diagnostics = diagnostics
            Runtime = {
                TargetFramework = "net10.0"
                Package = "Morphir.SDK.CSharp"
            }
        }

        try
            cancellationToken.ThrowIfCancellationRequested()

            if
                options.LanguageVersion
                <> 14
                && options.LanguageVersion
                   <> 15
            then
                Foundation.fail
                    "unsupported-language"
                    "$options/languageVersion"
                    "Only numeric C# 14 and 15 are supported."

            let versions =
                if model.Family = ModelFamily.Classic then
                    [ "1"; "2"; "3"; "3.0.0"; "3.1.0" ]
                else
                    [ "4"; "4.0.0" ]

            if not (List.contains model.SourceVersion.Text versions) then
                Foundation.fail
                    "unsupported-version"
                    "$sourceVersion"
                    "The source version is not supported for this model family."

            result GenerationStatus.Success (Foundation.sources model cancellationToken) []
        with
        | :? OperationCanceledException when cancellationToken.IsCancellationRequested ->
            result GenerationStatus.Cancelled [] []
        | Refusal diagnostic -> result GenerationStatus.Failure [] [ diagnostic ]
