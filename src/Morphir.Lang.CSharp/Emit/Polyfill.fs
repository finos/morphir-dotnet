namespace Morphir.Lang.CSharp.Emit

open Microsoft.CodeAnalysis
open Microsoft.CodeAnalysis.CSharp
open Microsoft.CodeAnalysis.CSharp.Syntax

/// <summary>
/// The file with the runtime types that C# 15 closed types and unions need and that .NET 10 and older lack. The types are
/// internal and only exist below .NET 11, so the file is the same for every target framework.
/// </summary>
module internal Polyfill =
    /// <summary>The path of the file.</summary>
    let path = "Morphir.Polyfill.g.cs"

    let private attributeUsage (targets: string list) (extras: (string * bool) list) : AttributeListSyntax =
        let targetsExpression =
            targets
            |> List.map (fun t -> Cs.access (Cs.globalGeneric [ "System"; "AttributeTargets" ] [] :> ExpressionSyntax) t)
            |> List.reduce (fun left right -> SF.BinaryExpression(SyntaxKind.BitwiseOrExpression, left, right) :> ExpressionSyntax)

        let arguments =
            [ yield SF.AttributeArgument targetsExpression
              for name, flag in extras ->
                  SF.AttributeArgument(SF.NameEquals(SF.IdentifierName name), null, Cs.boolLiteral flag) ]

        SF.AttributeList(
            SF.SingletonSeparatedList(
                SF.Attribute(Cs.globalName [ "System"; "AttributeUsage" ], SF.AttributeArgumentList(SF.SeparatedList<AttributeArgumentSyntax>(arguments)))
            )
        )

    let private attributeClass (name: string) (usage: AttributeListSyntax) : MemberDeclarationSyntax =
        SF.ClassDeclaration(Cs.token name)
            .WithAttributeLists(SF.SingletonList usage)
            .WithModifiers(Cs.modifiers [ SyntaxKind.InternalKeyword; SyntaxKind.SealedKeyword ])
            .WithBaseList(SF.BaseList(SF.SingletonSeparatedList<BaseTypeSyntax>(SF.SimpleBaseType(Cs.globalGeneric [ "System"; "Attribute" ] []))))
        :> MemberDeclarationSyntax

    /// <summary>The compilation unit of the polyfill file.</summary>
    let unit: CompilationUnitSyntax =
        let union =
            attributeClass "UnionAttribute" (attributeUsage [ "Class"; "Struct" ] [ "AllowMultiple", false ])

        let iunion =
            SF.InterfaceDeclaration(Cs.token "IUnion")
                .WithModifiers(Cs.modifiers [ SyntaxKind.InternalKeyword ])
                .WithMembers(
                    SF.SingletonList<MemberDeclarationSyntax>(
                        SF.PropertyDeclaration(SF.NullableType(Cs.keywordType SyntaxKind.ObjectKeyword), Cs.token "Value")
                            .WithAccessorList(SF.AccessorList(SF.SingletonList(SF.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(SF.Token SyntaxKind.SemicolonToken))))
                    )
                )
            :> MemberDeclarationSyntax

        let closed =
            attributeClass "IsClosedTypeAttribute" (attributeUsage [ "Class" ] [ "AllowMultiple", false; "Inherited", false ])

        let members = [ union; iunion; closed ]

        let ifNotNet11 =
            SF.IfDirectiveTrivia(
                SF.PrefixUnaryExpression(SyntaxKind.LogicalNotExpression, SF.IdentifierName "NET11_0_OR_GREATER"),
                true, true, true)

        let namespaceDeclaration =
            SF.FileScopedNamespaceDeclaration(Cs.dottedName [ "System"; "Runtime"; "CompilerServices" ])
                .WithMembers(
                    SF.List<MemberDeclarationSyntax>(
                        members |> List.mapi (fun i m ->
                            if i = 0 then m.WithLeadingTrivia(SF.Trivia ifNotNet11)
                            else m)
                    )
                )

        SF.CompilationUnit()
            .WithMembers(SF.SingletonList<MemberDeclarationSyntax>(namespaceDeclaration))
            .WithEndOfFileToken(SF.Token(SF.TriviaList(SF.Trivia(SF.EndIfDirectiveTrivia true)), SyntaxKind.EndOfFileToken, SF.TriviaList()))
            .WithLeadingTrivia(
                SF.Comment "// <auto-generated/>",
                SF.CarriageReturnLineFeed,
                SF.Trivia(SF.NullableDirectiveTrivia(SF.Token SyntaxKind.EnableKeyword, true))
            )
