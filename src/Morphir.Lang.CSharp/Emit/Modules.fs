namespace Morphir.Lang.CSharp.Emit

open System.Collections.Generic
open Microsoft.CodeAnalysis
open Microsoft.CodeAnalysis.CSharp
open Microsoft.CodeAnalysis.CSharp.Syntax
open Morphir.Lang.CSharp.Backend
open Morphir.IR
open ValueLowering

/// <summary>Assembles the files: one for each module that stands in a namespace, and one for each outermost static class.</summary>
module internal Modules =
    /// <summary>A node of the tree of nested static classes below a file root.</summary>
    type private ClassNode = {
        Name: string
        Module: ModulePath option
        Children: ClassNode list
    }

    let private values (context: Context) (checkedValues: Checked list) (path: ModulePath) =
        checkedValues
        |> List.filter (fun checkedValue -> checkedValue.Top.Name.ModulePath = path)
        |> List.map (Values.methodOf context)

    /// <summary>The members of a module: its types, then its methods.</summary>
    let private moduleMembers context checkedValues path : MemberDeclarationSyntax list =
        Declarations.ofModule context path @ values context checkedValues path

    /// <summary>The nested static classes below the root, as a tree that follows the container names.</summary>
    let private childrenOf (context: Context) (root: ModuleLayout) : ClassNode list =
        let rootLength = List.length root.Container

        let below =
            context.Layouts
            |> Map.toList
            |> List.map snd
            |> List.filter (fun layout -> layout.FileRoot = root.Path && layout.Path <> root.Path)
            |> List.map (fun layout -> layout.Container |> List.skip rootLength, layout.Path)

        let rec build (entries: (string list * ModulePath) list) : ClassNode list =
            entries
            |> List.groupBy (fun (segments, _) -> List.head segments)
            |> List.map (fun (name, group) ->
                let own = group |> List.tryFind (fun (segments, _) -> List.length segments = 1) |> Option.map snd
                let deeper = group |> List.filter (fun (segments, _) -> List.length segments > 1) |> List.map (fun (segments, path) -> List.tail segments, path)
                { Name = name; Module = own; Children = build deeper })

        build below

    let rec private staticClass (context: Context) checkedValues (isPublic: ModulePath -> bool) (node: ClassNode) : MemberDeclarationSyntax =
        let own = node.Module |> Option.map (moduleMembers context checkedValues) |> Option.defaultValue []
        let nested = node.Children |> List.map (staticClass context checkedValues isPublic)
        let accessKind = if node.Module |> Option.exists isPublic then SyntaxKind.PublicKeyword else SyntaxKind.InternalKeyword

        SF.ClassDeclaration(Cs.token node.Name)
            .WithModifiers(Cs.modifiers [ accessKind; SyntaxKind.StaticKeyword ])
            .WithMembers(SF.List<MemberDeclarationSyntax>(own @ nested))
        :> MemberDeclarationSyntax

    /// <summary>One compilation unit for each file, with its relative path.</summary>
    let compile
        (context: Context)
        (pkg: PackageName)
        (checkedValues: Checked list)
        (isPublic: ModulePath -> bool)
        : (string * CompilationUnitSyntax) list =
        context.Layouts
        |> Map.toList
        |> List.map snd
        |> List.filter (fun layout -> layout.FileRoot = layout.Path)
        |> List.choose (fun root ->
            context.Ct.ThrowIfCancellationRequested()

            let members: MemberDeclarationSyntax list =
                match root.Kind with
                | NamespaceOnly -> moduleMembers context checkedValues root.Path
                | StaticClass ->
                    let name = List.last root.Container
                    let node = { Name = name; Module = Some root.Path; Children = childrenOf context root }
                    [ staticClass context checkedValues isPublic node ]

            if List.isEmpty members then
                None
            else
                let unit =
                    SF.CompilationUnit()
                        .WithMembers(
                            SF.SingletonList<MemberDeclarationSyntax>(
                                SF.FileScopedNamespaceDeclaration(Cs.dottedName root.Namespace).WithMembers(SF.List<MemberDeclarationSyntax>(members))
                            )
                        )
                        .WithLeadingTrivia(
                            SF.Comment "// <auto-generated/>",
                            SF.CarriageReturnLineFeed,
                            SF.Trivia(SF.NullableDirectiveTrivia(SF.Token SyntaxKind.EnableKeyword, true))
                        )

                Some(TypeEmission.sourcePath pkg root.Path, unit))
