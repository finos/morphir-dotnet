namespace Morphir;

/// <summary>
/// The source of the polyfill file for a C# 15 <c>union</c> and <c>closed record</c> on a target framework that lacks the
/// runtime types of the language feature. The types are <c>internal</c> and behind framework guards, so each assembly has
/// its own copy and the file is empty on a framework that has them. The compiler finds the types by name.
/// </summary>
/// <remarks>
/// The backend writes this text as a file of the generated assembly, the package adds it to a model project, and the
/// frontend adds it to the compilation of <c>morphir compile</c>, which binds against fixed reference assemblies.
/// </remarks>
public static class Polyfill
{
    /// <summary>The file name of the polyfill file.</summary>
    public const string FileName = "MorphirPolyfill.g.cs";

    /// <summary>The text of the polyfill file.</summary>
    public const string Source = """
        // <auto-generated/>
        #nullable enable
        namespace System.Runtime.CompilerServices
        {
        #if !NET5_0_OR_GREATER
            internal static class IsExternalInit { }
        #endif
        #if !NET7_0_OR_GREATER
            [System.AttributeUsage(System.AttributeTargets.All, AllowMultiple = true, Inherited = false)]
            internal sealed class CompilerFeatureRequiredAttribute : System.Attribute
            {
                public CompilerFeatureRequiredAttribute(string featureName) { FeatureName = featureName; }
                public string FeatureName { get; }
                public bool IsOptional { get; set; }
            }
        #endif
        #if !NET11_0_OR_GREATER
            [System.AttributeUsage(System.AttributeTargets.Class | System.AttributeTargets.Struct, AllowMultiple = false)]
            internal sealed class UnionAttribute : System.Attribute { }
            internal interface IUnion { object? Value { get; } }
            [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            internal sealed class IsClosedTypeAttribute : System.Attribute { }
        #endif
        }
        """;
}
