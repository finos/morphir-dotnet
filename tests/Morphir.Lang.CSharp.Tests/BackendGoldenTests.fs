module Morphir.Lang.CSharp.Tests.BackendGoldenTests

open System.Threading
open Expecto
open Morphir.Compilation
open Morphir.Lang.CSharp
open Morphir.Lang.CSharp.Tests.BackendSupport

let private expectCompiles (files: Map<string, string>) =
    Expect.equal (compileErrors files) [] "the generated code compiles as C# 15"

let private header = "// <auto-generated/>\n#nullable enable\n"

let private geoShapes =
    moduleOf
        [ "point", alias [] (recordT [ "x", intT; "y", intT ])
          "shape", custom [] [ "circle", [ "radius", floatT ]; "rect", [ "w", floatT; "h", floatT ] ] ]
        []

[<Tests>]
let tests =
    testList "C# backend on Roslyn: golden output" [
        test "a module that has only types is written at namespace level" {
            let files = generate (library [ "shapes", geoShapes ])
            let text = files["p_Acme.Geo/m_ShapesModule.g.cs"]

            Expect.equal
                text
                (header
                 + "namespace Acme.Geo.Shapes;\n"
                 + "public sealed record Point(int X, int Y);\n"
                 + "public closed record Shape;\n"
                 + "public sealed record Circle(double Radius) : global::Acme.Geo.Shapes.Shape;\n"
                 + "public sealed record Rect(double W, double H) : global::Acme.Geo.Shapes.Shape;\n")
                "the types stand in the namespace, with no static class"

            expectCompiles files
        }

        test "a module that has values is a static class in the namespace of the modules above it" {
            let files =
                generate (
                    library
                        [ "shapes", geoShapes
                          "shapes/geometry", moduleOf [] [ "double", definition [ "x", intT ] intT (apply (apply (reference "shapes/geometry#times") (variable "x")) (int 2))
                                                           "times", definition [ "a", intT; "b", intT ] intT (variable "a") ] ]
                )

            let text = files["p_Acme.Geo/m_Shapes_GeometryModule.g.cs"]
            Expect.stringContains text "namespace Acme.Geo.Shapes;\npublic static class Geometry\n{\n" "a static class named after the module"
            Expect.stringContains text "public static int Double(int x) => global::Acme.Geo.Shapes.Geometry.Times(x, 2);" "a saturated call is a direct call"
            expectCompiles files
        }

        test "a module below a static-class module is a nested static class, also when it has only types" {
            let files =
                generate (
                    library
                        [ "pricing", moduleOf [] [ "base", definition [] intT (int 1) ]
                          "pricing/discounts", moduleOf [ "rate", alias [] (recordT [ "percent", intT ]) ] [] ]
                )

            Expect.isTrue (files.ContainsKey "p_Acme.Geo/m_PricingModule.g.cs") "one file for the outermost class"
            Expect.isFalse (files.ContainsKey "p_Acme.Geo/m_Pricing_DiscountsModule.g.cs") "no file for the nested module"
            let text = files["p_Acme.Geo/m_PricingModule.g.cs"]

            Expect.equal
                text
                (header
                 + "namespace Acme.Geo;\n"
                 + "public static class Pricing\n{\n"
                 + "    public static int Base() => 1;\n"
                 + "    public static class Discounts\n    {\n"
                 + "        public sealed record Rate(int Percent);\n"
                 + "    }\n"
                 + "}\n")
                "the nested module is a nested static class"

            expectCompiles files
        }

        test "a class between a static-class module and a public module below it is public, also with no module of its own" {
            let files =
                generate (
                    library
                        [ "pricing", moduleOf [] [ "base", definition [] intT (int 1) ]
                          "pricing/rules/discounts", moduleOf [] [ "rate", definition [] intT (int 2) ] ]
                )

            let text = files["p_Acme.Geo/m_PricingModule.g.cs"]
            Expect.stringContains text "    public static class Rules\n" "the class Rules has no module, and a public module is below it"
            let assembly = load files

            match assembly.GetType "Acme.Geo.Pricing+Rules" with
            | null -> failtest "no class Rules"
            | rules -> Expect.isTrue rules.IsNestedPublic "a consumer can reach Pricing.Rules.Discounts"

            expectCompiles files
        }

        test "a generic record keeps its type parameters and their notnull constraint" {
            let files = generate (library [ "pairs", moduleOf [ "pair", alias [ "a"; "b" ] (recordT [ "first", variableT "a"; "second", variableT "b" ]) ] [] ])

            Expect.equal
                files["p_Acme.Geo/m_PairsModule.g.cs"]
                (header
                 + "namespace Acme.Geo.Pairs;\n"
                 + "public sealed record Pair<TA, TB>(TA First, TB Second)\n    where TA : notnull\n    where TB : notnull;\n")
                "a plain positional record"

            expectCompiles files
        }

        test "a custom type with wrapper constructors is a union of the wrapped types" {
            let model =
                library
                    [ "shapes",
                      moduleOf
                          [ "circle", alias [] (recordT [ "radius", floatT ])
                            "rect", alias [] (recordT [ "w", floatT; "h", floatT ])
                            "shape", custom [] [ "circle", [ "circle", own "shapes" "circle" [] ]; "rect", [ "rect", own "shapes" "rect" [] ] ] ]
                          [] ]

            let files = generate model
            let text = files["p_Acme.Geo/m_ShapesModule.g.cs"]
            Expect.stringContains text "public union Shape(global::Acme.Geo.Shapes.Circle, global::Acme.Geo.Shapes.Rect);" "union Shape(Circle, Rect)"
            Expect.isFalse (text.Contains "closed record") "no closed record"
            expectCompiles files
        }

        test "a custom type with a constructor that has fields is a closed record with sealed cases" {
            let files = generate (library [ "prices", moduleOf [ "price", custom [] [ "quote", [ "value", floatT ]; "none", [] ] ] [] ])

            Expect.equal
                files["p_Acme.Geo/m_PricesModule.g.cs"]
                (header
                 + "namespace Acme.Geo.Prices;\n"
                 + "public closed record Price;\n"
                 + "public sealed record None : global::Acme.Geo.Prices.Price;\n"
                 + "public sealed record Quote(double Value) : global::Acme.Geo.Prices.Price;\n")
                "closed record Price with the sealed record Quote"

            expectCompiles files
        }

        test "a custom type that mixes the two shapes takes the closed form" {
            let model =
                library
                    [ "mixed",
                      moduleOf
                          [ "wrapped", alias [] (recordT [ "n", intT ])
                            "either", custom [] [ "wrapped", [ "wrapped", own "mixed" "wrapped" [] ]; "other", [ "x", intT ] ] ]
                          [] ]

            // The case Wrapped and the type Wrapped share a name in the closed form.
            let diagnostics = refuse model
            Expect.equal (diagnostics |> List.map (fun d -> d.Rule)) [ "name-collision" ] "the rule"
            Expect.stringContains (List.head diagnostics).Message "Wrapped" "names the case and the type"
        }

        test "a mixed custom type whose wrapped type is in another module is a closed record with sealed cases" {
            let model =
                library
                    [ "shapes", moduleOf [ "wrapped", alias [] (recordT [ "n", intT ]) ] []
                      "mixed",
                      moduleOf [ "either", custom [] [ "wrapped", [ "value", own "shapes" "wrapped" [] ]; "other", [ "x", intT ] ] ] [] ]

            let files = generate model
            let text = files["p_Acme.Geo/m_MixedModule.g.cs"]
            Expect.stringContains text "public closed record Either;" "the closed form"
            Expect.stringContains text "public sealed record Wrapped(global::Acme.Geo.Shapes.Wrapped Value) : global::Acme.Geo.Mixed.Either;" "the wrapper case is a sealed record"
            Expect.stringContains text "public sealed record Other(int X) : global::Acme.Geo.Mixed.Either;" "the other case"
            Expect.isFalse (text.Contains "union") "no union"
            expectCompiles files
        }

        test "a case with the name of another type of the module is a name collision that names both" {
            let model =
                library
                    [ "prices",
                      moduleOf
                          [ "quote", alias [] (recordT [ "n", intT ])
                            "price", custom [] [ "quote", [ "value", floatT ] ] ]
                          [] ]

            let diagnostics = refuse model
            Expect.equal (diagnostics |> List.map (fun d -> d.Rule)) [ "name-collision" ] "the rule"
            let message = (List.head diagnostics).Message
            Expect.stringContains message "Quote" "the case"
            Expect.stringContains message "Price" "the custom type"
        }

        test "each generated output has the polyfill file with the five types of the PRD behind their guards" {
            let plain = generate (library [ "pairs", moduleOf [ "point", alias [] (recordT [ "x", intT ]) ] [] ])
            Expect.isTrue (plain.ContainsKey "Morphir.Polyfill.g.cs") "a model with only records also gets the polyfill file"
            let text = plain["Morphir.Polyfill.g.cs"]

            let guarded (guard: string) (declaration: string) =
                let at = text.IndexOf("#if " + guard + "\n")
                Expect.isGreaterThanOrEqual at 0 $"the guard {guard}"
                let close = text.IndexOf("#endif", at)
                let inside = text.Substring(at, close - at)
                Expect.stringContains inside declaration $"{declaration} is behind {guard}"

            guarded "!NET5_0_OR_GREATER" "internal static class IsExternalInit"
            guarded "!NET7_0_OR_GREATER" "internal sealed class CompilerFeatureRequiredAttribute"
            guarded "!NET7_0_OR_GREATER" "public CompilerFeatureRequiredAttribute(string featureName)"
            guarded "!NET11_0_OR_GREATER" "internal sealed class UnionAttribute"
            guarded "!NET11_0_OR_GREATER" "internal interface IUnion"
            guarded "!NET11_0_OR_GREATER" "internal sealed class IsClosedTypeAttribute"
            Expect.stringContains text "namespace System.Runtime.CompilerServices" "the namespace of the runtime types"
            Expect.equal text Morphir.Polyfill.Source "the same text that the frontend adds to its compilation"

            let withClosed = generate (library [ "prices", moduleOf [ "price", custom [] [ "quote", [ "value", floatT ] ] ] [] ])
            Expect.equal withClosed["Morphir.Polyfill.g.cs"] text "the file is the same for every model"
        }

        test "each arm of a switch expression and its closing brace are on a line of their own" {
            let model =
                library
                    [ "shapes",
                      moduleOf
                          [ "shape", custom [] [ "circle", [ "radius", floatT ]; "square", [ "edge", floatT ]; "rect", [ "w", floatT; "h", floatT ] ] ]
                          [ "size",
                            definition
                                [ "s", own "shapes" "shape" [] ]
                                floatT
                                (patternMatch
                                    (variable "s")
                                    [ constructorPattern "shapes#circle" [ asPattern "r" ], variable "r"
                                      constructorPattern "shapes#square" [ asPattern "e" ], variable "e"
                                      constructorPattern "shapes#rect" [ asPattern "w"; asPattern "h" ], variable "w" ]) ] ]

            let files = generate model

            Expect.equal
                files["p_Acme.Geo/m_ShapesModule.g.cs"]
                (header
                 + "namespace Acme.Geo;\n"
                 + "public static class Shapes\n{\n"
                 + "    public closed record Shape;\n"
                 + "    public sealed record Circle(double Radius) : global::Acme.Geo.Shapes.Shape;\n"
                 + "    public sealed record Rect(double W, double H) : global::Acme.Geo.Shapes.Shape;\n"
                 + "    public sealed record Square(double Edge) : global::Acme.Geo.Shapes.Shape;\n"
                 + "    public static double Size(global::Acme.Geo.Shapes.Shape s) => s switch\n"
                 + "    {\n"
                 + "        global::Acme.Geo.Shapes.Circle(var r) => r,\n"
                 + "        global::Acme.Geo.Shapes.Square(var e) => e,\n"
                 + "        global::Acme.Geo.Shapes.Rect(var w, var h) => w\n"
                 + "    };\n"
                 + "}\n")
                "three arms, each on its own line, and the closing brace on its own line; no discard arm for a closed type"

            expectCompiles files
        }

        test "the layout pass puts every switch expression of a file in the layout, also after the 64th" {
            let methods = [ for index in 1..70 -> $"    int F{index}(int s) => s switch {{ 1 => 2, _ => 3 }};\n" ] |> String.concat ""
            let text = Morphir.Lang.CSharp.Emit.Format.fixSwitches ("class C\n{\n" + methods + "}\n")
            let lines = text.Split '\n'
            Expect.equal (lines |> Array.filter (fun line -> line.Trim() = "1 => 2,") |> Array.length) 70 "each first arm is on a line of its own"
            Expect.equal (lines |> Array.filter (fun line -> line.Trim() = "};") |> Array.length) 70 "each closing brace is on a line of its own"
        }

        test "the layout pass parses the text as C# 15, the language version of the backend" {
            Expect.equal Morphir.Lang.CSharp.Emit.Format.languageVersion Microsoft.CodeAnalysis.CSharp.LanguageVersion.CSharp15 "C# 15, not the preview version"
        }

        test "two runs give the same bytes" {
            let model = library [ "shapes", geoShapes; "shapes/geometry", moduleOf [] [ "one", definition [] intT (int 1) ] ]
            Expect.equal (generate model) (generate model) "deterministic"
        }
    ]
