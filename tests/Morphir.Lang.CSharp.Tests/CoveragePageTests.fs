module Morphir.Lang.CSharp.Tests.CoveragePageTests

open System
open System.IO
open System.Text
open Expecto
open Morphir.Lang.CSharp.Analyzers

let private pagePath =
    Path.GetFullPath(
        Path.Combine(__SOURCE_DIRECTORY__, "..", "..", "docs", "content", "docs", "frontends", "csharp", "coverage.md")
    )

let private anchor (code: string) = code.Replace('.', '-').Replace('_', '-')

/// The coverage page, generated from the rule catalog of the analyzer assembly.
let private page () =
    let text = StringBuilder()
    let line (value: string) = text.Append(value).Append('\n') |> ignore

    line "---"
    line "title: \"C# frontend coverage\""
    line "linkTitle: \"Coverage\""
    line "weight: 20"
    line "description: \"The C# constructs that the C# frontend refuses, with their diagnostic codes, Roslyn ids and examples.\""
    line "---"
    line ""
    line "<!-- Generated from Morphir.Lang.CSharp.Analyzers.Rules.All in src/Morphir.Lang.CSharp.Analyzers/Rules.cs."
    line "     Do not edit this file. To update it, run the Morphir.Lang.CSharp.Tests project with"
    line "     UPDATE_SNAPSHOTS=1. -->"
    line ""
    line "The C# frontend compiles a subset of C# 15. After the C# compiler binds the documents without an error, an admission"
    line "analyzer refuses each construct outside the subset with an error diagnostic. All refusals of a run are reported"
    line "together, and the frontend writes no model. The [overview](../) describes the supported subset."
    line ""
    line "The same analyzer runs in the compiler, in the IDE and in `morphir compile`, so a refusal has one code, one message"
    line "and one range everywhere. A rule cannot be turned off: `#pragma warning disable`, `.editorconfig` and `NoWarn`"
    line "do not hide it, and a `SuppressMessage` attribute that names a rule is refused with `MORPHIR1008`. A construct"
    line "that a rule refuses cannot become a model, so change the construct. The absolute IRI of a rule is the help link"
    line "of its diagnostic. Codes are stable once released."
    line ""
    line "## Codes"
    line ""
    line "| Code | Roslyn id | Construct |"
    line "| --- | --- | --- |"

    for rule in Rules.All do
        line $"| [`{rule.Code}`](#{anchor rule.Code}) | `{rule.Id}` | {rule.Title} |"

    for rule in Rules.All do
        line ""
        line $"## `{rule.Code}`"
        line ""
        line $"- Roslyn id: `{rule.Id}`"
        let message = rule.Message.Replace("{0}", "…").Replace("{1}", "…")
        line ("- Message: " + message)
        line $"- IRI: `{rule.Iri}`"
        line ""

        if rule.Id = Rules.OutsideReference.Id then
            line "The analyzer reports a symbol from an assembly that the fixed reference set does not have. `morphir compile`"
            line "cannot bind such a symbol, so the C# compiler reports it first as `csharp.compiler`."
        else
            line "Example:"
            line ""
            line "```csharp"
            line rule.Example
            line "```"

    text.ToString()

[<Tests>]
let tests =
    testList
        "C# frontend coverage page"
        [ test "the page matches the rule catalog" {
              let expected = page ()

              if Environment.GetEnvironmentVariable "UPDATE_SNAPSHOTS" = "1" then
                  Directory.CreateDirectory(Path.GetDirectoryName(pagePath) |> string) |> ignore
                  File.WriteAllText(pagePath, expected, UTF8Encoding(false))

              Expect.isTrue (File.Exists pagePath) $"{pagePath} exists; run with UPDATE_SNAPSHOTS=1"
              Expect.equal (File.ReadAllText pagePath) expected "The page is generated from the catalog; run with UPDATE_SNAPSHOTS=1"
          } ]
