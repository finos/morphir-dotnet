/// The generated coverage reference of the F# frontend (FSF-3). The admission catalog is its only
/// source: the test fails when the page in the docs differs from the catalog.
module Morphir.Frontend.FSharp.Tests.CoverageTests

open System
open System.IO
open Expecto
open Morphir.Frontend.FSharp.Analysis

/// The path of the page, relative to the repository root.
let pagePath = "docs/content/docs/frontends/fsharp/coverage.md"

/// The heading id of a rule. Explicit ids keep the links stable when the heading text changes.
let private anchor (code: string) =
    code.Replace('.', '-').Replace('_', '-')

/// Text for one Markdown table cell.
let private cell (text: string) = text.Replace("|", "\\|")

/// Renders the coverage reference from the catalog rules, in catalog order.
let internal render (rules: AdmissionRule list) =
    let specific =
        rules
        |> List.filter (fun rule -> not rule.IsFallback)

    let fallbacks =
        rules
        |> List.filter (fun rule -> rule.IsFallback)

    let row (rule: AdmissionRule) =
        $"| [`{rule.Code}`](#{anchor rule.Code}) | {cell rule.Construct} |"

    let section (rule: AdmissionRule) = [
        $"### `{rule.Code}` {{#{anchor rule.Code}}}"
        ""
        $"**Construct:** {rule.Construct}"
        ""
        $"**Message:** {rule.Message}"
        ""
        match rule.Suggestion with
        | Some suggestion ->
            $"**Suggestion:** {suggestion}"
            ""
        | None -> ()
        match rule.Flagged with
        | "" ->
            "**Example.** The diagnostic is an empty range at the start of the first document."
            ""
        | flagged when flagged.Contains '\n' ->
            "**Example.** The diagnostic is at this text:"
            ""
            "```fsharp"
            flagged
            "```"
            ""
        | flagged ->
            $"**Example.** The diagnostic is at `{flagged}`."
            ""
        for uri, text in rule.Example do
            $"`{uri}`:"
            ""
            "```fsharp"
            text.TrimEnd('\n')
            "```"
            ""
    ]

    [
        "---"
        "title: \"F# frontend coverage\""
        "linkTitle: \"Coverage\""
        "weight: 20"
        "description: \"The F# constructs that the F# frontend refuses, with their diagnostic codes and examples.\""
        "---"
        ""
        "<!-- Generated from AdmissionCatalog.rules in src/Morphir.Frontend.FSharp/AdmissionCatalog.fs."
        "     Do not edit this file. To update it, run the Morphir.Frontend.FSharp.Tests project with"
        "     UPDATE_SNAPSHOTS=1. -->"
        ""
        "The F# frontend compiles a subset of F#. Before it lowers a document, admission checks the"
        "syntax and refuses each construct outside the subset with an error diagnostic. All refusals"
        "of a run are reported together, and the frontend writes no model. The"
        "[overview](../) describes the supported subset."
        ""
        "This page is generated from the admission catalog of the frontend, so it lists every code"
        "that admission can report. Each rule has a minimal example that gives only its own code. The"
        "conformance corpus has one refusal case for each code. Codes are stable once released."
        ""
        "## Codes"
        ""
        "| Code | Construct |"
        "| --- | --- |"
        for rule in specific do
            row rule
        ""
        "The fallback rules below refuse any expression, pattern, type or declaration outside the"
        "supported subset that no specific rule refused."
        ""
        "| Code | Construct |"
        "| --- | --- |"
        for rule in fallbacks do
            row rule
        ""
        "## Rules"
        ""
        for rule in
            specific
            @ fallbacks do
            yield! section rule
    ]
    |> String.concat "\n"

let private repositoryRoot =
    Path.GetFullPath(Path.Combine(__SOURCE_DIRECTORY__, "..", ".."))

[<Tests>]
let tests =
    testList "F# frontend coverage reference" [
        test "The published coverage page equals the page generated from the catalog" {
            let page = Path.Combine(repositoryRoot, pagePath)
            let generated = render AdmissionCatalog.rules

            if Environment.GetEnvironmentVariable "UPDATE_SNAPSHOTS" = "1" then
                Directory.CreateDirectory(Path.GetDirectoryName page)
                |> ignore

                File.WriteAllText(page, generated)

            let published =
                if File.Exists page then
                    File.ReadAllText(page).Replace("\r\n", "\n")
                else
                    ""

            Expect.equal
                published
                generated
                $"{pagePath} differs from the catalog. To update it, run the tests with UPDATE_SNAPSHOTS=1."
        }
        |> testLabel "PlatformSpecific"

        test "Every catalog code appears once in the page, with its message and an example" {
            let generated = render AdmissionCatalog.rules

            for rule in AdmissionCatalog.rules do
                let heading = $"### `{rule.Code}` {{#{anchor rule.Code}}}"

                let headings =
                    generated.Split('\n')
                    |> Array.filter (fun line -> line = heading)

                Expect.equal headings.Length 1 $"{rule.Code} has one section"

                let start = generated.IndexOf(heading, StringComparison.Ordinal)

                let next =
                    generated.IndexOf(
                        "\n### ",
                        start
                        + heading.Length,
                        StringComparison.Ordinal
                    )

                let body =
                    if next < 0 then
                        generated.Substring start
                    else
                        generated.Substring(
                            start,
                            next
                            - start
                        )

                Expect.stringContains body rule.Message $"{rule.Code} has its message"
                Expect.stringContains body "```fsharp" $"{rule.Code} has an example"

                for _, text in rule.Example do
                    Expect.stringContains
                        body
                        (text.TrimEnd('\n'))
                        $"{rule.Code} has its example text"
        }
    ]
